#include <iostream>
using namespace std;

int main(){
    int a = 1, b = 2, c = 3;//declares a, b, and c as int, and assigns values to them
    cout << a + b + c << endl;//prints the sum of a + b + c, then adds a newline

    int x, y, z;//declares x, y, and z as int
    x = y = z = 0;//sets x, y, and z as int, and assigns 0 to them
    cout << x + y + z << endl;//prints the sum of x + y + z, then adds a newline
    return 0;
}