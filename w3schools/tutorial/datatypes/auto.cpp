#include <iostream>
using namespace std;

int main(){
    auto num = 10;//sets num as an integer because 10 is an integer
    auto dec = 5.5;//sets dec as a double because 5.5 is a double
    auto letter = 'A';//sets letter as a char because 'A is a character

    cout << "Integer: " << num << endl;
    cout << "Double: " << dec << endl;
    cout << "Character: " << letter << endl;

    return 0;
}