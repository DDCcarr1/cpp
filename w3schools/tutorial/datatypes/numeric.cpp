#include <iostream>
using namespace std;

int main(){
    int myInt = 5;//declares myInt is 5, an int
    cout << "myInt: " << myInt << endl;//prints myInt, then adds a newline

    float myFloat = 5.99;//declares myFloat is 5.99, a float
    cout << "myFloat: " << myFloat << endl;//prints myFloat, then adds a newline

    double myDouble = 9.98;//declares myDouble is 9.98, a double
    cout << "myDouble: " << myDouble << endl;//prints myDouble, then adds a newline

    return 0;
}