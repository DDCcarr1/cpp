#include <cmath>
#include <iostream>
using namespace std;

int main(){
    cout << max(5, 10) << endl;//prints the maximum of 5 and 10, then adds a newline
    cout << min(5, 10) << endl;//prints the minimum of 5
    cout << sqrt(64) << endl;//prints the square root of 64, then adds a newline
    cout << round(2.6) << endl;//prints 3, then adds a
    cout << log(2) << endl;//prints the natural logarithm of 2, then adds a newline

    return 0;
}